s as (
  select r.* from recipes r join seed on seed.name = r.name
)
select
  count(*)                                          as 合計,
  count(*) filter (where dish_type = 'main')        as 主菜,
  count(*) filter (where dish_type = 'side')        as 副菜,
  count(*) filter (where dish_type = 'soup')        as 汁物,
  count(*) filter (where dish_type='main' and main_protein='meat') as 肉,
  count(*) filter (where dish_type='main' and main_protein='fish') as 魚,
  count(*) filter (where dish_type='main' and main_protein='soy')  as 大豆,
  count(*) filter (where dish_type='main' and main_protein='egg')  as 卵,
  count(*) filter (where dish_type='main' and category='washoku')  as 和,
  count(*) filter (where dish_type='main' and category='yoshoku')  as 洋,
  count(*) filter (where dish_type='main' and category='chuka')    as 中
from s;
