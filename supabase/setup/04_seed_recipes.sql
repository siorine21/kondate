-- 3) 食材マスタ（仕様書 11.2）
--    材料から自動生成する。調味料は常備品として買い物リストに出さない。
insert into ingredient_master (household_id, name, shop_category, default_unit, is_pantry)
select distinct on (r.household_id, ri.name)
       r.household_id,
       ri.name,
       ri.shop_category,
       ri.unit,
       ri.shop_category = 'seasoning'
from recipe_ingredients ri
join recipes r on r.id = ri.recipe_id
order by r.household_id, ri.name, ri.sort_order
on conflict (household_id, name) do nothing;

