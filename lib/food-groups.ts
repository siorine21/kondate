/* 材料1つを見る。当たらなければ 0（群なし）。 */
export function groupOf(name: string): number {
  const key = name.trim();
  if (key === "" || NO_GROUP_EXACT.has(key)) return NONE;
  const hit = HINTS.find(([word]) => key.includes(word));
  return hit ? hit[1] : NONE;
}

/* レシピの材料から食品群を出す。小さい順に並べて返す。 */
export function guessFoodGroups(ingredientNames: readonly string[]): number[] {
  const found = new Set<number>();
  for (const name of ingredientNames) {
    const group = groupOf(name);
    if (group !== NONE) found.add(group);
  }
  return [...found].sort((a, b) => a - b);
}
